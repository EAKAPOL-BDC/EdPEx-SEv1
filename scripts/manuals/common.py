"""Editorial building blocks shared by the web and downloadable manuals."""

VERSION = '1.2'
UPDATED = '17 กันยายน 2569'
BASELINE = '056124d96c109c51826505f6d9c03f3652a4fc60'


def section(key, title, paragraphs=(), steps=(), columns=(), rows=(), checks=(), note='', flow=(), code=''):
    return dict(id=key, title=title, paragraphs=list(paragraphs),
                steps=[dict(title=t, action=a, expected=e) for t, a, e in steps],
                columns=list(columns), rows=[list(r) for r in rows], checks=list(checks),
                note=note, flow=[dict(title=t, detail=d) for t,d in flow], code=code)


def manual(slug, title, audience, summary, sections, *, category='operations', group='', forms=(), permissions=()):
    return dict(slug=slug, title=title, audience=audience, summary=summary,
        category=category, group=group, forms=list(forms), permissions=list(permissions),
        access='public' if category == 'respondents' else 'authenticated',
        version=VERSION, updated=UPDATED, baseline=BASELINE,
        sections=sections, filename='nexora-'+slug+'.pdf')


